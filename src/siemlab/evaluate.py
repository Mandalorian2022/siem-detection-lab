"""Score alerts and incidents against the scenario ground truth.

Attribution is by evidence: an alert belongs to a scenario if any event it
cites was generated by that scenario. That is stricter than overlapping
time windows and immune to the "right rule, wrong reason" error.

For each scenario and each detection it expects:
  TP  an attributed alert from that detection exists
  FN  none does (a known gap is reported separately, not as a miss)
Alerts not attributed to any scenario fired on baseline traffic: FP.
Alerts attributed to a benign scenario are FP unless the scenario lists
the detection as expected, in which case they are benign true positives,
counted as TP and flagged, because an analyst still had to look.

Per-detection precision and recall follow from those counts. Time to
detect is measured from the scenario's first event to the alert's first
evidence. Incident quality is measured on the multi-stage campaign: how
many of its stages ended up in one incident, and how many incidents it
was split across.
"""
from __future__ import annotations

import json
from collections import defaultdict
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .incidents import Incident
from .model import Alert, parse_ts


@dataclass
class DetectionScore:
    name: str
    tp: int = 0
    fp: int = 0
    fn: int = 0
    benign_tp: int = 0
    extra: int = 0
    alerts: int = 0

    @property
    def precision(self) -> float | None:
        return self.tp / (self.tp + self.fp) if self.tp + self.fp else None

    @property
    def recall(self) -> float | None:
        return self.tp / (self.tp + self.fn) if self.tp + self.fn else None

    @property
    def f1(self) -> float | None:
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if p is not None and r is not None and p + r else None


@dataclass
class ScenarioResult:
    id: str
    name: str
    malicious: bool
    expected: list[str]
    fired: list[str]
    missed: list[str]
    unexpected: list[str]
    known_gap: bool
    time_to_detect_s: float | None
    campaign: str | None
    stage: int | None
    techniques: list[str]


@dataclass
class Report:
    seed: int
    events: int
    alerts: int
    incidents: int
    scenarios: list[ScenarioResult]
    detections: dict[str, dict]
    overall: dict
    baseline_false_positives: list[dict]
    campaign: dict
    attack_coverage: dict[str, list[str]]
    alerts_per_day: float
    noise: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)


def evaluate(alerts: list[Alert], incidents: list[Incident], truth: dict, catalogue: list[dict],
             n_events: int, days: int = 5) -> Report:
    ev2scn: dict[str, str] = truth["event_scenario"]
    scenarios = {s["id"]: s for s in truth["scenarios"]}
    names = {c["name"] for c in catalogue}
    scores = {n: DetectionScore(n) for n in sorted(names)}

    by_campaign: dict[str, list[str]] = defaultdict(list)
    for sid, s in scenarios.items():
        if s.get("campaign"):
            by_campaign[s["campaign"]].append(sid)

    attributed: dict[str, list[Alert]] = defaultdict(list)
    baseline_fp: list[Alert] = []
    for a in alerts:
        scores[a.rule_id].alerts += 1
        hit = {ev2scn[e] for e in a.evidence if e in ev2scn}
        if not hit:
            baseline_fp.append(a)
            scores[a.rule_id].fp += 1
            continue
        # a campaign is one continuous intrusion: an alert whose evidence spans two
        # stages, or lands on the stage next to the one that expects it, still counts
        for sid in list(hit):
            camp = scenarios[sid].get("campaign")
            if camp:
                hit |= {o for o in by_campaign[camp] if a.rule_id in scenarios[o]["expected"]}
        for sid in hit:
            attributed[sid].append(a)

    results: list[ScenarioResult] = []
    ttd: list[float] = []
    for sid, s in scenarios.items():
        fired_rules = {a.rule_id for a in attributed[sid]}
        expected = set(s["expected"])
        missed = sorted(expected - fired_rules)
        unexpected = sorted(fired_rules - expected)
        for r in expected & fired_rules:
            scores[r].tp += 1
            if not s["malicious"]:
                scores[r].benign_tp += 1
        for r in missed:
            if not s["known_gap"]:
                scores[r].fn += 1
        for r in unexpected:
            # firing on an attack the scenario did not list is extra coverage, not a
            # false positive; firing on a benign look-alike that did not expect it is
            if s["malicious"]:
                scores[r].extra += 1
            else:
                scores[r].fp += 1
        t = None
        if s["malicious"] and attributed[sid]:
            first = min(parse_ts(a.first_seen) for a in attributed[sid] if a.rule_id in expected) \
                if expected & fired_rules else None
            if first is not None:
                t = max(0.0, first - s["start"])
                ttd.append(t)
        results.append(ScenarioResult(sid, s["name"], s["malicious"], sorted(expected),
                                      sorted(fired_rules), missed, unexpected, s["known_gap"], t,
                                      s.get("campaign"), s.get("stage"), s["techniques"]))

    tp = sum(x.tp for x in scores.values())
    fp = sum(x.fp for x in scores.values())
    fn = sum(x.fn for x in scores.values())
    overall = {
        "tp": tp, "fp": fp, "fn": fn,
        "precision": round(tp / (tp + fp), 3) if tp + fp else None,
        "recall": round(tp / (tp + fn), 3) if tp + fn else None,
        "benign_true_positives": sum(x.benign_tp for x in scores.values()),
        "extra_detections_on_attacks": sum(x.extra for x in scores.values()),
        "known_gaps": sum(1 for s in scenarios.values() if s["known_gap"]),
        "malicious_scenarios": sum(1 for s in scenarios.values() if s["malicious"]),
        "benign_scenarios": sum(1 for s in scenarios.values() if not s["malicious"]),
        "median_time_to_detect_s": round(sorted(ttd)[len(ttd) // 2], 1) if ttd else None,
        "mean_time_to_detect_s": round(sum(ttd) / len(ttd), 1) if ttd else None,
    }

    # campaign: which incidents hold its stages
    camp_ids = [sid for sid, s in scenarios.items() if s.get("campaign")]
    camp_alert_ids = {a.alert_id for sid in camp_ids for a in attributed[sid]}
    holders = [i for i in incidents if set(i.alert_ids) & camp_alert_ids]
    best = max(holders, key=lambda i: len(set(i.alert_ids) & camp_alert_ids), default=None)
    best_ids = set(best.alert_ids) if best else set()
    stages_in_best = sorted(scenarios[sid]["stage"] for sid in camp_ids
                            if any(a.alert_id in best_ids for a in attributed[sid]))
    campaign = {"stages": len(camp_ids), "stages_detected":
                sum(1 for sid in camp_ids if attributed[sid]),
                "incidents_touched": len(holders),
                "largest_incident": best.incident_id if best else None,
                "largest_incident_risk": best.risk if best else None,
                "stages_in_largest_incident": stages_in_best}

    coverage: dict[str, set[str]] = defaultdict(set)
    for c in catalogue:
        for t in c["techniques"]:
            coverage[t].add(c["name"])
    noise = {"baseline_alerts": len(baseline_fp),
             "alerts_on_benign_lookalikes": sum(len(attributed[s]) for s in scenarios
                                                if not scenarios[s]["malicious"]),
             "incidents_by_severity": dict(sorted(
                 ((sev, sum(1 for i in incidents if i.severity == sev))
                  for sev in ("critical", "high", "medium", "low", "informational")),
                 key=lambda kv: kv[0]))}
    return Report(truth["seed"], n_events, len(alerts), len(incidents), results,
                  {n: {**asdict(s), "precision": s.precision, "recall": s.recall, "f1": s.f1}
                   for n, s in scores.items()},
                  overall, [a.to_dict() for a in baseline_fp], campaign,
                  {t: sorted(v) for t, v in sorted(coverage.items())},
                  round(len(alerts) / days, 1), noise)


def load_truth(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)
